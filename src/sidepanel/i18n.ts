export function translate(locale: Locale, key: string, values: Values = {}) {
  let message = locale === 'zh' ? zh[key] || key : key;
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{{${name}}}`, String(value));
  }
  return message;
}
